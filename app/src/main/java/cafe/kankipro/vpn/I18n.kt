/** زبان اپ: fa یا en */
object LangState {
    var lang by mutableStateOf("fa")
    val en get() = lang == "en"
}

/** متن فارسی را در حالت انگلیسی ترجمه می‌کند (برای متن‌های بدون ترجمه، همان متن برمی‌گردد) */
fun tr(fa: String): String {
    if (!LangState.en) return fa
    EN[fa]?.let { return it }
    var out = fa
    for ((k, v) in PHRASES) if (out.contains(k)) out = out.replace(k, v)
    return out
}

/** ترجمه + جای‌گذاری عدد/متن (مثل «فقط %d روز مونده») */
fun trf(fa: String, vararg args: Any): String = String.format(java.util.Locale.US, tr(fa), *args)

